import Foundation

var failed=0
func check(_ condition:Bool,_ message:String){
    if !condition {failed+=1;fputs("FAIL "+message+"\n",stderr)}
}

let body=Data("{\"error\":\"workspace_lock\",\"workspaces\":[{\"id\":\"11111111-1111-1111-1111-111111111111\",\"name\":\"Photos\",\"issue\":\"over_cap\"},{\"id\":\"22222222-2222-2222-2222-222222222222\",\"name\":\"Archive\",\"reason\":\"unpaid\"}]}".utf8)
let route=CloudSignals.route(status:423,body:body,method:"PUT")
check(route.destination == .lockScreen,"chunk 423 destination")
check(route.method == "PUT","chunk method")
check(route.toast == nil,"chunk 423 has no toast")
check(route.lock?.workspaces.first?.name == "Photos","workspace name")
check(route.lock?.workspaces.first?.issue == "over_cap","over cap")
check(route.lock?.workspaces.first?.label == "Photos · over the plan cap","over cap label")
check(route.lock?.workspaces.last?.issue == "unpaid","unpaid")
check(route.lock?.issueSummary == "Some workspaces are over the plan cap or unpaid.","issue summary")
let shown=CloudSignals.present(route:CloudSignals.routeLock,message:nil)
check(shown.lockScreen && shown.toast == nil,"lock presentation has no toast")
check(CloudSignals.allowsTransfer(method:"PUT",locked:true) == false,"uploads pause")
check(CloudSignals.allowsTransfer(method:"GET",locked:true),"downloads continue")
check(CloudSignals.allowsTransfer(method:"HEAD",locked:true),"reads continue")
let ok=CloudSignals.route(status:200,body:Data("{\"ok\":true}".utf8),method:"GET")
check(ok.destination == .cont && ok.toast == nil,"success has no toast")
let generic=CloudSignals.route(status:500,body:Data("{\"error\":\"unavailable\"}".utf8),method:"PUT")
check(generic.destination == .genericError && generic.toast == "unavailable","generic error still reports")
let genericShown=CloudSignals.present(route:nil,message:"unavailable")
check(!genericShown.lockScreen && genericShown.toast == "unavailable","generic toast")

let payload=Data("{\"auth_time\":1700000000}".utf8).base64EncodedString()
    .replacingOccurrences(of:"+",with:"-").replacingOccurrences(of:"/",with:"_").replacingOccurrences(of:"=",with:"")
let jwt="eyJhbGciOiJub25lIn0."+payload+"."
let auth=Date(timeIntervalSince1970:1_700_000_000)
check(CloudSignals.freshSignIn(jwt,now:auth.addingTimeInterval(300)),"five minutes is fresh")
check(!CloudSignals.freshSignIn(jwt,now:auth.addingTimeInterval(300.001)),"older than five minutes is stale")
let refreshed=Data("{\"iat\":1700003600,\"auth_time\":1700000000}".utf8).base64EncodedString()
    .replacingOccurrences(of:"+",with:"-").replacingOccurrences(of:"/",with:"_").replacingOccurrences(of:"=",with:"")
check(!CloudSignals.freshSignIn("eyJhbGciOiJub25lIn0."+refreshed+".",now:Date(timeIntervalSince1970:1_700_003_600)),"refresh iat does not replace auth_time")

func ready()->AccountDeletion {
    var flow=AccountDeletion()
    flow.continueFromExplain()
    check(flow.confirmPhrase("DELETE"),"confirm")
    check(flow.acceptFreshSignIn(authTime:Date(timeIntervalSince1970:1),now:Date(timeIntervalSince1970:1)),"fresh")
    flow.noteDeleteSent()
    return flow
}
var gated=AccountDeletion()
check(!gated.confirmPhrase("DELETE"),"phrase before explain")
gated.continueFromExplain()
check(!gated.confirmPhrase("delete"),"phrase is exact")
check(gated.confirmPhrase("DELETE"),"phrase accepted")
let now=Date(timeIntervalSince1970:10_000)
check(!gated.acceptFreshSignIn(authTime:now.addingTimeInterval(-301),now:now),"old sign-in rejected")
check(gated.step == .reauth && (gated.message ?? "").contains("5 minutes"),"stale copy")

var progress=ready()
progress.onDeleteHttp(status:202,jobId:"job_1",errorCode:nil)
check(progress.step == .polling && progress.statusPath == AccountDeletion.deletionStatusPath+"job_1","poll path")
check(AccountDeletion.deletionStatusPath == "/v2/account/deletions/","plural status path")
progress.onPollHttp(status:200,state:"queued",errorCode:nil)
check(progress.step == .polling && !progress.requestsWipe(),"queued stays in progress")
progress.onPollHttp(status:200,state:"running",errorCode:nil)
check(progress.step == .polling,"running stays in progress")
progress.onPollHttp(status:200,state:"done",errorCode:nil)
check(progress.requestsWipe() && progress.step == .done,"done wipes")

var broken=ready()
broken.onDeleteHttp(status:202,jobId:"job_2",errorCode:nil)
broken.onPollHttp(status:200,state:"failed",errorCode:nil)
check(broken.step == .failed && !broken.requestsWipe(),"failed can retry")
check(LocalWipePlan.keychainServicesRemoved(wipe:broken.requestsWipe()).isEmpty,"failed does not clear keychain")

var reauth=ready()
reauth.onDeleteHttp(status:401,jobId:nil,errorCode:"reauth_required")
check(reauth.step == .reauth && !reauth.requestsWipe(),"reauth_required does not wipe")
check(LocalWipePlan.keychainServicesRemoved(wipe:reauth.requestsWipe()).isEmpty,"401 does not clear keychain")
check(reauth.acceptFreshSignIn(authTime:Date(timeIntervalSince1970:5),now:Date(timeIntervalSince1970:5)),"second sign-in")
reauth.noteDeleteSent()
reauth.onDeleteHttp(status:401,jobId:nil,errorCode:"reauth_required")
check(reauth.step == .reauth && !reauth.requestsWipe(),"another 401 still does not wipe")
check(LocalWipePlan.keychainServicesRemoved(wipe:reauth.requestsWipe()).isEmpty,"second 401 does not clear keychain")

var invalid=ready()
invalid.onDeleteHttp(status:401,jobId:nil,errorCode:"invalid_token")
check(invalid.step == .signedOut && !invalid.requestsWipe(),"invalid_token signs out")
check(LocalWipePlan.keychainServicesRemoved(wipe:invalid.requestsWipe()).isEmpty,"invalid_token does not wipe keychain")

var polling=ready()
polling.onDeleteHttp(status:202,jobId:"job_3",errorCode:nil)
polling.onPollHttp(status:401,state:nil,errorCode:"reauth_required")
check(polling.step == .reauth && !polling.requestsWipe(),"poll 401 does not wipe")
check(polling.acceptFreshSignIn(authTime:Date(timeIntervalSince1970:6),now:Date(timeIntervalSince1970:6)),"resume after reauth")
check(polling.step == .polling,"existing job resumes polling")
polling.onPollHttp(status:401,state:nil,errorCode:"invalid_token")
check(polling.step == .signedOut && LocalWipePlan.keychainServicesRemoved(wipe:polling.requestsWipe()).isEmpty,"poll invalid_token does not wipe")

