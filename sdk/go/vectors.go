package gendragoon

import (
	"crypto/ecdh"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
)

// TestVectors builds the cross-language vectors in spec/vectors/v1.json from fixed inputs. Every SDK
// checks its implementation against that file; `go run ./cmd/gd-vectors` regenerates it.
func TestVectors() ([]byte, error) {
	fill := func(n int, b byte) []byte {
		out := make([]byte, n)
		for i := range out {
			out[i] = b + byte(i)
		}
		return out
	}
	h := hex.EncodeToString
	mk := fill(32, 0x10)
	fk := fill(32, 0x40)
	type kv = map[string]any
	var hk []kv
	for _, p := range []string{"manifest-name", "manifest-enc", "chunk-id", "chunk-enc"} {
		ikm := mk
		if p == "chunk-id" || p == "chunk-enc" {
			ikm = fk
		}
		hk = append(hk, kv{"ikm": h(ikm), "purpose": p, "out": h(SubKey(ikm, p))})
	}
	pass := "correct horse battery staple"
	envScrypt, err := WrapMasterKey(mk, pass, KDF{Alg: "scrypt", N: 1 << 14, R: 8, P: 1}, 1, fixedReader(fill(28, 0x70)))
	if err != nil {
		return nil, err
	}
	envArgon, err := WrapMasterKey(mk, pass, KDF{Alg: "argon2id", MemoryKiB: 19456, Iterations: 2, Parallelism: 1}, 1, fixedReader(fill(28, 0x90)))
	if err != nil {
		return nil, err
	}
	chunkPT := []byte("hello, gendragoon")
	chunkNonce := fill(12, 0xa0)
	chunkID, chunkBlob := sealChunkNonce(fk, chunkPT, chunkNonce)
	drive := "saves"
	mkey := DriveManifestKey(mk, drive)
	doc := `{"v":1,"encrypted":true,"files":{"slot1.sav":{"size":17,"mtime":1800000000000,"sha256":"` + sha256hex(chunkPT) +
		`","chunks":["` + chunkID + `"],"key":"` + b64.EncodeToString(fk) + `"}},"folders":["levels"],"updatedAt":1800000000000}`
	manNonce := fill(12, 0xb0)
	sealedMan := sealManifestNonce(mk, mkey, []byte(doc), manNonce)
	rpriv, _ := ecdh.P256().NewPrivateKey(fill(32, 0x01))
	epriv, _ := ecdh.P256().NewPrivateKey(fill(32, 0x02))
	shareNonce := fill(12, 0xc0)
	payload := `{"v":1,"path":"slot1.sav","entry":{"size":17,"mtime":1800000000000,"sha256":"` + sha256hex(chunkPT) +
		`","chunks":["` + chunkID + `"],"key":"` + b64.EncodeToString(fk) + `"}}`
	share, err := sealShareWith(epriv, rpriv.PublicKey(), []byte(payload), shareNonce)
	if err != nil {
		return nil, err
	}
	verifier := b64.EncodeToString(fill(32, 0x20))
	vs := sha256.Sum256([]byte(verifier))
	out := kv{
		"comment":          "Generated by sdk/go/cmd/gd-vectors. Formats: sdk/spec/FORMATS.md.",
		"hkdf":             hk,
		"envelopeScrypt":   kv{"passphrase": pass, "masterKey": h(mk), "envelope": envScrypt},
		"envelopeArgon2id": kv{"passphrase": pass, "masterKey": h(mk), "envelope": envArgon},
		"chunk":            kv{"fileKey": h(fk), "plaintext": h(chunkPT), "nonce": h(chunkNonce), "id": chunkID, "blob": h(chunkBlob)},
		"manifest": kv{"masterKey": h(mk), "driveName": drive, "manifestKey": mkey, "plainManifestKey": DriveManifestKey(nil, drive),
			"nonce": h(manNonce), "plaintext": doc, "sealed": h(sealedMan)},
		"share": kv{"recipientPrivate": h(rpriv.Bytes()), "recipientPublic": (&Identity{rpriv}).Public(), "ephemeralPrivate": h(epriv.Bytes()),
			"nonce": h(shareNonce), "payload": payload, "share": share},
		"pkce": kv{"verifier": verifier, "challenge": b64.EncodeToString(vs[:])},
	}
	return json.MarshalIndent(out, "", " ")
}

func sha256hex(b []byte) string { s := sha256.Sum256(b); return hex.EncodeToString(s[:]) }

type fixedReaderT struct{ b []byte }

func fixedReader(b []byte) *fixedReaderT { return &fixedReaderT{b} }

func (r *fixedReaderT) Read(p []byte) (int, error) {
	n := copy(p, r.b)
	r.b = r.b[n:]
	return n, nil
}
